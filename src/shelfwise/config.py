"""Runtime settings (environment variables with the SHELFWISE_ prefix, or .env) and the store's YAML configuration."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Annotated, Any, Literal

import yaml
from pydantic import AliasChoices, Field, field_validator
from pydantic_settings import BaseSettings, NoDecode, SettingsConfigDict

LLMProviderKind = Literal["fake", "openrouter", "openai", "compat"]

REPO_ROOT = Path(__file__).resolve().parents[2]

# Chosen with `shelfwise eval smoke` on 2026-10-13 (results/smoke_*.json): free OpenRouter models only. The Gemma 4
# vision models were rate-limited upstream on every request that day; the Inkling models refuse non-agent apps.
DEFAULT_FREE_TEXT_MODEL = "nvidia/nemotron-3-super-120b-a12b:free"
DEFAULT_FREE_TEXT_FALLBACKS = ["nvidia/nemotron-3-ultra-550b-a55b:free"]
DEFAULT_FREE_VISION_MODEL = "dots-studio/dots-3-note-preview:free"
DEFAULT_FREE_VISION_FALLBACKS = ["nvidia/nemotron-3-nano-omni-30b-a3b-reasoning:free"]
DEFAULT_TEXT_MODELS: dict[str, str] = {
    "fake": "fake-rules",
    "openrouter": DEFAULT_FREE_TEXT_MODEL,
    "openai": "gpt-5-mini",
    "compat": "",
}
DEFAULT_VISION_MODELS: dict[str, str] = {
    "fake": "fake-pixels",
    "openrouter": DEFAULT_FREE_VISION_MODEL,
    "openai": "gpt-5-mini",
    "compat": "",
}


def _split(value: object) -> object:
    if isinstance(value, str):
        return [item.strip() for item in value.split(",") if item.strip()]
    return value


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", env_prefix="SHELFWISE_", extra="ignore")

    # ---- storage and inputs
    database: Path = Path(".cache/shelfwise.db")
    workspace_dir: Path = Path(".cache/workspace")
    """Uploaded feeds and images, exports."""
    demo_dir: Path = REPO_ROOT / "data" / "demo"
    """The bundled synthetic catalog (feeds, images, gold labels), written by `shelfwise seed`."""
    store_config: Path = REPO_ROOT / "configs" / "store.yaml"
    style_guide: Path = REPO_ROOT / "configs" / "style_guide.yaml"
    seed_demo: bool = True
    """On API start: import the demo feeds when the database is empty."""
    results_dir: Path = REPO_ROOT / "results"
    cors_origins: Annotated[list[str], NoDecode] = Field(default_factory=lambda: ["http://localhost:3000"])

    # ---- the mock stores (no real store, no account)
    shopify_url: str = "http://127.0.0.1:8000/mock/shopify"
    shopify_api_version: str = "2026-07"
    shopify_token: str = ""
    """Empty = the mock's local development token (generated by the mock at start, never a real token)."""
    woocommerce_url: str = "http://127.0.0.1:8000/mock/woocommerce"

    # ---- LLM
    llm_provider: LLMProviderKind = "fake"
    text_model: str = ""
    vision_model: str = ""
    text_fallback_models: Annotated[list[str], NoDecode] = Field(default_factory=list)
    vision_fallback_models: Annotated[list[str], NoDecode] = Field(default_factory=list)
    require_free_models: bool = True
    allow_paid_models: bool = False
    """The explicit opt-in for paid models (SHELFWISE_ALLOW_PAID_MODELS=true). Off by default: a fresh clone refuses
    every OpenRouter or `compat` model id that does not end in ":free"."""
    llm_base_url: str = ""
    """Endpoint of the `compat` provider (any OpenAI-compatible /chat/completions server)."""
    llm_api_key: str | None = None
    llm_send_temperature: bool = True
    llm_timeout_seconds: float = 180.0
    llm_max_tokens: int = 8000
    llm_reasoning_effort: str = "low"
    """OpenRouter reasoning effort for the vision and copy calls ("off" disables reasoning)."""
    translate_reasoning_effort: str = "off"
    """Translation needs no reasoning: with it off, a free reasoning model answers in about 10 s instead of 60 s."""
    llm_max_calls: int = 3000
    """Hard cap on real requests per ledger file (retries included)."""
    llm_min_seconds_between_requests: float = 3.0
    llm_max_retries: int = 4
    llm_cache: bool = True
    llm_cache_dir: Path = Path(".cache/llm")
    llm_ledger: Path | None = REPO_ROOT / "results" / "calls.jsonl"
    llm_concurrency: int = 2
    """Products enriched in parallel (the request throttle is shared, so this only overlaps model latency)."""
    copy_retries: int = 1
    """Corrective rewrites when the first listing fails validation."""

    openrouter_api_key: str | None = Field(default=None, validation_alias=AliasChoices("OPENROUTER_API_KEY"))
    openrouter_base_url: str = Field(
        default="https://openrouter.ai/api/v1", validation_alias=AliasChoices("OPENROUTER_BASE_URL")
    )
    openai_api_key: str | None = Field(default=None, validation_alias=AliasChoices("OPENAI_API_KEY"))
    openai_base_url: str = Field(default="https://api.openai.com/v1", validation_alias=AliasChoices("OPENAI_BASE_URL"))

    # ---- MCP
    mcp_max_output_chars: int = 24_000

    @field_validator("text_fallback_models", "vision_fallback_models", "cors_origins", mode="before")
    @classmethod
    def _split_lists(cls, value: object) -> object:
        return _split(value)

    @field_validator("llm_ledger", mode="before")
    @classmethod
    def _empty_ledger(cls, value: object) -> object:
        return None if value in ("", None) else value

    @property
    def free_only(self) -> bool:
        return self.require_free_models and not self.allow_paid_models

    def text_model_name(self) -> str:
        return self.text_model or DEFAULT_TEXT_MODELS[self.llm_provider]

    def vision_model_name(self) -> str:
        return self.vision_model or DEFAULT_VISION_MODELS[self.llm_provider]

    def text_fallbacks(self) -> list[str]:
        if self.text_fallback_models or self.llm_provider != "openrouter" or self.text_model:
            return self.text_fallback_models
        return list(DEFAULT_FREE_TEXT_FALLBACKS)

    def vision_fallbacks(self) -> list[str]:
        if self.vision_fallback_models or self.llm_provider != "openrouter" or self.vision_model:
            return self.vision_fallback_models
        return list(DEFAULT_FREE_VISION_FALLBACKS)


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    return Settings()


# ---------------------------------------------------------------- store configuration


@dataclass(frozen=True)
class Limit:
    min: int = 0
    max: int = 10_000


@dataclass(frozen=True)
class BannedClaim:
    pattern: re.Pattern[str]
    reason: str


@dataclass
class StoreConfig:
    name: str
    currency: str
    languages: list[str]
    fx: dict[str, float]
    product_types: list[str]
    title: Limit
    meta_title: Limit
    meta_description: Limit
    bullets_count: Limit
    bullet_max_chars: int
    body_words: Limit
    alt_text_max: int
    tags_count: Limit
    translation_slack: float
    banned: list[BannedClaim]
    needs_evidence: dict[str, list[str]]
    style: dict[str, Any] = field(default_factory=dict)

    @property
    def glossary_keep(self) -> list[str]:
        return list(self.style.get("glossary", {}).get("keep", []))

    @property
    def glossary_terms(self) -> dict[str, dict[str, str]]:
        return dict(self.style.get("glossary", {}).get("terms", {}))

    @property
    def avoid_words(self) -> list[str]:
        return list(self.style.get("avoid_words", []))


def _limit(data: dict[str, Any], lo: str = "min", hi: str = "max") -> Limit:
    return Limit(int(data.get(lo, 0)), int(data.get(hi, 10_000)))


def load_store_config(store_path: Path, style_path: Path) -> StoreConfig:
    raw = yaml.safe_load(store_path.read_text(encoding="utf-8"))
    style = yaml.safe_load(style_path.read_text(encoding="utf-8")) if style_path.exists() else {}
    store, limits, claims = raw["store"], raw["limits"], raw["claims"]
    return StoreConfig(
        name=store["name"],
        currency=store["currency"],
        languages=list(store.get("languages", [])),
        fx={k.upper(): float(v) for k, v in store.get("fx_to_store_currency", {}).items()},
        product_types=list(store.get("product_types", [])),
        title=_limit(limits["title"]),
        meta_title=_limit(limits["meta_title"]),
        meta_description=_limit(limits["meta_description"]),
        bullets_count=_limit(limits["bullets"], "min_count", "max_count"),
        bullet_max_chars=int(limits["bullets"].get("max_chars", 160)),
        body_words=_limit(limits["body"], "min_words", "max_words"),
        alt_text_max=int(limits["alt_text"]["max_chars"]),
        tags_count=_limit(limits["tags"], "min_count", "max_count"),
        translation_slack=float(limits.get("translation_length_slack", 1.15)),
        banned=[BannedClaim(re.compile(b["pattern"], re.IGNORECASE), b["reason"]) for b in claims.get("banned", [])],
        needs_evidence={k: [s.lower() for s in v] for k, v in claims.get("needs_evidence", {}).items()},
        style=style or {},
    )


@lru_cache(maxsize=4)
def _cached_store(store_path: str, style_path: str) -> StoreConfig:
    return load_store_config(Path(store_path), Path(style_path))


def get_store(settings: Settings | None = None) -> StoreConfig:
    s = settings or get_settings()
    return _cached_store(str(s.store_config), str(s.style_guide))
