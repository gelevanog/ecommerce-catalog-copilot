export type Evidence = { source: string; ref: string; quote: string };
export type Fact = { key: string; value: unknown; display: string; evidence: Evidence[]; id: string };
export type Issue = { code: string; severity: "error" | "warning" | "info"; message: string; field: string; span: string; waived: string };
export type Variant = {
  sku: string;
  options: Record<string, string>;
  price: number | null;
  currency: string;
  source_price: string;
  inventory: number | null;
  weight_g: number | null;
  gtin: string | null;
  source: { file: string; row: number };
};
export type Product = {
  id: string;
  handle: string;
  supplier_file: string;
  title_raw: string;
  vendor: string | null;
  supplier_category: string;
  facts: Fact[];
  variants: Variant[];
  images: string[];
  notes_raw: string;
  merged_duplicates: { file: string; row: number }[];
  issues: Issue[];
};
export type ImageAttributes = {
  image: string;
  model: string;
  color: string | null;
  secondary_color: string | null;
  pattern: string | null;
  material: string | null;
  style: string | null;
  count: number | null;
  product_noun: string;
  confidence: Record<string, number>;
  raw: Record<string, unknown>;
  error: string;
};
export type Decision = {
  attribute: string;
  value: unknown;
  status: "agree" | "conflict" | "feed_only" | "image_only" | "missing";
  feed_value: unknown;
  image_value: unknown;
  evidence: Evidence[];
  needs_review: boolean;
  note: string;
};
export type Translated = { title: string; body_html: string; bullets: string[]; meta_title: string; meta_description: string };
export type Listing = Translated & {
  tags: string[];
  product_type: string;
  category_id: number | null;
  category_path: string;
  alt_texts: string[];
  translations: Record<string, Translated>;
};
export type FieldReview = { state: "pending" | "approved" | "edited"; by: string; at: string };
export type CallStats = { calls: number; cached: number; input_tokens: number; output_tokens: number; seconds: number; models: string[] };
export type ProductRecord = {
  id: string;
  batch_id: string;
  status: string;
  product: Product;
  image_attributes: ImageAttributes[];
  decisions: Decision[];
  generated: Listing | null;
  listing: Listing | null;
  provenance: Record<string, string[]>;
  issues: Issue[];
  review: Record<string, FieldReview>;
  stats: CallStats;
  copy_attempts: string[][];
  error: string;
};
export type Card = {
  id: string;
  status: string;
  handle: string;
  name: string;
  title: string;
  title_raw: string;
  vendor: string | null;
  image: string | null;
  product_type: string;
  variants: number;
  errors: number;
  warnings: number;
  conflicts: string[];
  attributes: Record<string, unknown>;
  languages: string[];
  supplier: string;
};
export type ProductsResponse = { batch_id: string | null; counts: Record<string, number>; total: number; products: Card[] };
export type ProductDetail = {
  record: ProductRecord;
  name: string;
  category_candidates: { id: number; path: string }[];
  category: { id: number; path: string } | null;
  events: AuditEvent[];
};
export type AuditEvent = { id: number; at: string; actor: string; action: string; product_id: string | null; detail: Record<string, unknown> };
export type StoreConfigInfo = {
  store: string;
  currency: string;
  languages: string[];
  product_types: string[];
  limits: Record<string, number | number[]>;
  models: Record<string, string>;
  taxonomy: string;
  voice: string;
  banned: string[];
};
export type Mapping = { column: string; target: string | null; method: string; confidence: number; samples: string[] };
export type Preview = { file: string; header_row: number; columns: string[]; rows: number; sample: string[][]; mapping: Mapping[] };
